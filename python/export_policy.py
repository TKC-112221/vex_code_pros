"""Write a trained SAC actor into the firmware weight table.

The deployed network is the actor mean: Linear-SiLU-Linear-SiLU-Linear.
The firmware applies tanh and scales to ±12 V, which is the deterministic
SAC action. log_std stays in the checkpoint and is not exported.

    python python/export_policy.py python/drive_policy.zip
"""

import sys
from pathlib import Path

import numpy as np
import torch
from torch import nn

sys.path.insert(0, str(Path(__file__).resolve().parent))

ROOT = Path(__file__).resolve().parents[1]
HEADER = ROOT / "include" / "control" / "DrivePolicyWeights.h"
CSV = ROOT / "data" / "drive_policy.csv"


def actor_linears(model):
    actor = model.policy.actor
    hidden = [module for module in actor.latent_pi.modules() if isinstance(module, nn.Linear)]
    if not hidden:
        raise SystemExit("actor.latent_pi has no Linear layers; the SAC policy layout changed")
    return hidden + [actor.mu]


def pack_weights(linears):
    blobs = []
    for layer in linears:
        weight = layer.weight.detach().cpu().numpy().astype(np.float32)
        bias = layer.bias.detach().cpu().numpy().astype(np.float32)
        blobs.append(np.ascontiguousarray(weight).reshape(-1))
        blobs.append(np.ascontiguousarray(bias).reshape(-1))
    return np.concatenate(blobs)


def write_header(weights, sizes):
    lines = [
        "#pragma once",
        "/* ---------------------------------------------------------------------------",
        " * DrivePolicyWeights  --  generated by python/export_policy.py.",
        " * Do not edit. Re-run the exporter after training.",
        f" * Actor layers: {', '.join(str(n) for n in sizes)}. SiLU hidden, linear out.",
        " * Each layer is row-major weights[out][in], then biases[out].",
        " * ------------------------------------------------------------------------- */",
        "",
        "namespace DrivePolicyWeights {",
        "",
        "constexpr bool kReady = true;",
        f"constexpr int kCount = {weights.size};",
        "constexpr float kValues[kCount] = {",
    ]
    for value in weights:
        lines.append(f"    {float(value):.8e}f,")
    lines.append("};")
    lines.append("")
    lines.append("}")
    lines.append("")
    HEADER.write_text("\n".join(lines), encoding="utf-8")


def write_csv(weights, sizes):
    CSV.parent.mkdir(parents=True, exist_ok=True)
    header = "# layers " + ",".join(str(n) for n in sizes) + "\n"
    body = "\n".join(f"{float(value):.8e}" for value in weights)
    CSV.write_text(header + body + "\n", encoding="utf-8")


def check_against_plant(weights, sizes):
    try:
        import plant
    except ImportError:
        print("plant module is not built; skipped the firmware forward-pass check")
        return
    if list(sizes) != list(plant.LAYER_SIZES):
        raise SystemExit(f"actor sizes {list(sizes)} do not match the firmware {list(plant.LAYER_SIZES)}")
    if weights.size != plant.WEIGHT_COUNT:
        raise SystemExit(f"packed {weights.size} floats, firmware expects {plant.WEIGHT_COUNT}")
    if not plant.assign_weights(weights.tolist()):
        raise SystemExit("firmware rejected the weight table")

    # History frames are (v_surge, v_sway, v_yaw, a_surge, a_yaw), newest
    # first, in m/s, rad/s, and normalized commands. Lookahead is body-frame
    # meters. A slow straight, full throttle, 1.5 in left.
    frames = [0.0] * int(plant.HISTORY)
    v_surge = frames.copy()
    v_surge[0] = 0.2
    v_yaw = frames.copy()
    v_yaw[0] = -0.1
    look_x = [0.2, 0.5, 1.0, 1.4]
    look_y = [0.02, 0.05, 0.08, 0.1]
    sample = (
        v_surge, frames, v_yaw, frames, frames,
        look_x, look_y, 0.4, 0.1, 1.0, 1.5,
    )
    surge, sway, yaw = plant.command(*sample)
    reading = plant.read_policy(*sample)
    with torch.no_grad():
        x = torch.tensor(reading.features, dtype=torch.float32)
        y = x
        # Replay the exported linears the same way NeuralNetwork::predict does.
        cursor = 0
        for index, (in_n, out_n) in enumerate(zip(sizes, sizes[1:])):
            count = out_n * in_n
            weight = torch.tensor(weights[cursor:cursor + count].reshape(out_n, in_n))
            cursor += count
            bias = torch.tensor(weights[cursor:cursor + out_n])
            cursor += out_n
            y = weight @ y + bias
            if index < len(sizes) - 2:
                y = torch.nn.functional.silu(y)
        y = torch.tanh(y) * plant.MAX_VOLTS
    got = np.array([surge, yaw], dtype=np.float64)
    expect = y.numpy().astype(np.float64)
    if abs(float(sway)) > 1e-6:
        raise SystemExit(f"firmware sway command is {sway}; the differential actor leaves it at zero")
    if not np.allclose(got, expect, atol=1e-4):
        raise SystemExit(f"firmware command {got} disagrees with the exported actor {expect}")
    print("firmware forward pass matches the exported actor")


def export(checkpoint):
    import train_drive_policy  # noqa: F401  (checkpoint names this policy class)
    from stable_baselines3 import SAC

    model = SAC.load(checkpoint, device="cpu")
    linears = actor_linears(model)
    sizes = [linears[0].in_features] + [layer.out_features for layer in linears]
    weights = pack_weights(linears)
    write_header(weights, sizes)
    write_csv(weights, sizes)
    print(f"wrote {HEADER}")
    print(f"wrote {CSV} ({weights.size} floats, layers {sizes})")
    check_against_plant(weights, sizes)


def main():
    if len(sys.argv) != 2:
        raise SystemExit("usage: python python/export_policy.py python/drive_policy.zip")
    export(Path(sys.argv[1]))


if __name__ == "__main__":
    main()
